    def _iface(self, cls, sub, proto, eps, first_seen=0.0) -> Interface:
        return Interface(bInterfaceClass=cls, bInterfaceSubClass=sub,
                         bInterfaceProtocol=proto, endpoints=tuple(eps),
                         first_seen_ts=first_seen)

    def _descriptor(self, vendor_key, bus, devnum, ifaces) -> DeviceDescriptor:
        vid, pid = self.rng.choice(VENDORS[vendor_key])
        return DeviceDescriptor(
            bus=bus, devnum=devnum, vid=vid, pid=pid, bDeviceClass=0x00,
            serial_present=self.rng.random() < 0.7,
            manufacturer=vendor_key, product=vendor_key,
            interfaces=tuple(ifaces),
        )

    _HID_EPS = (Endpoint(0x81, "intr", 10),)
    _STORAGE_EPS = (Endpoint(0x81, "bulk"), Endpoint(0x02, "bulk"))

    def session(self, sid: str, profile: str, duration: float | None = None
                ) -> SimulatedSession:
        rng = self.rng
        bus = rng.randint(1, 3)
        dev = self._devnum
        self._devnum = 2 + (self._devnum - 1) % 120
        lines: list[str] = []
        onset: float | None = None
        # One persona per session, drawn before the profile branch so benign and
        # malicious devices are varied by the same prior.
        self._persona = self._sample_persona()

        # ONE duration distribution for every profile. If malicious sessions
        # ran longer than benign ones the models could separate them on session
        # length alone, which is leakage rather than detection (plan §5).
        dur = duration if duration is not None else rng.uniform(*DURATION_RANGE)

        def hid_desc():
            return self._descriptor("keyboard", bus, dev,
                                    [self._iface(CLASS_HID, 0x01, 0x01, self._HID_EPS)])

        if profile == "keyboard":
            d, label = hid_desc(), 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            self._human_typing(t, dur - t, bus, dev, lines)

        elif profile == "mouse":
            d = self._descriptor("mouse", bus, dev,
                                 [self._iface(CLASS_HID, 0x01, 0x02,
                                              (Endpoint(0x81, "intr", 8),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            self._mouse_motion(t, dur - t, bus, dev, lines)

        elif profile == "mass_storage":
            d = self._descriptor("mass_storage", bus, dev,
                                 [self._iface(CLASS_MASS_STORAGE, 0x06, 0x50,
                                              self._STORAGE_EPS)])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._bulk_io(t, dur - t, bus, dev, lines)

        elif profile == "webcam":
            d = self._descriptor("webcam", bus, dev,
                                 [self._iface(CLASS_VIDEO, 0x01, 0x00,
                                              (Endpoint(0x83, "iso"),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._iso_stream(t, dur - t, bus, dev, lines)

        elif profile == "audio":
            d = self._descriptor("audio", bus, dev,
                                 [self._iface(CLASS_AUDIO, 0x02, 0x00,
                                              (Endpoint(0x83, "iso"),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._iso_stream(t, dur - t, bus, dev, lines, period=0.005, size=192)

        elif profile == "hid_injection":
            # Descriptor is INDISTINGUISHABLE from a real keyboard, which is
            # what defeats USBGuard-style whitelisting entirely.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(1.5, 4.0)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._injected_typing(onset, dur - onset, bus, dev, lines)

        elif profile == "identity_switch":
            # Enumerates as storage, later exposes an HID interface and injects.
            onset = rng.uniform(15, 30)
            d = self._descriptor("mass_storage", bus, dev, [
                self._iface(CLASS_MASS_STORAGE, 0x06, 0x50, self._STORAGE_EPS),
                self._iface(CLASS_HID, 0x01, 0x01, (Endpoint(0x83, "intr", 10),),
                            first_seen=onset),
            ])
            label = 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid, n_ifaces=2)
            self._bulk_io(t, onset - t, bus, dev, lines)
            # the late interface enumerates its own HID class requests
            self._hid_class_setup(lines, onset, bus, dev)
            self._injected_typing(onset, dur - onset, bus, dev, lines, ep=3)

        elif profile == "staged_delay":
            # Passes as a human-driven keyboard for a long dwell, then fires.
            # Onset is a FRACTION of the session, not an absolute 30-45 s: the
            # absolute form forced a longer duration draw and leaked the label
            # through session length (CLAUDE.md §4 defect 4).
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = dur * rng.uniform(0.45, 0.62)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._injected_typing(onset, dur - onset, bus, dev, lines,
                                  mean_iat=0.004, jitter=0.25)

        elif profile == "mimicry":
            # Hardest case: correct keyboard descriptor AND human-calibrated
            # timing. Only structural and long-horizon cues remain.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(4, 12)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._mimicry_typing(onset, dur - onset, bus, dev, lines)

        elif profile == "mimicry_adaptive":
            # Same descriptor and same timing as mimicry, but the payload is
            # typed once instead of cycled. See _adaptive_typing.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(4, 12)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._adaptive_typing(onset, dur - onset, bus, dev, lines)

        elif profile == "class_exfil":
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(5, 12)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._covert_bulk_out(onset, dur - onset, bus, dev, lines)

        # --- single-axis diagnostics (pillar N1) --------------------------
        # Onset is immediate: these isolate a modality, and a dwell period
        # would only add pre-onset benign windows that dilute the measurement.
        elif profile == "axis_timing":
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = t
            self._axis_timing(t, dur - t, bus, dev, lines)

        elif profile == "axis_payload":
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = t
            self._axis_payload(t, dur - t, bus, dev, lines)

        elif profile == "axis_protocol":
            # The OUT endpoint is DECLARED, so using it is not an identity
            # deviation -- only a protocol one.
            d = self._descriptor("keyboard", bus, dev, [
                self._iface(CLASS_HID, 0x01, 0x01,
                            (Endpoint(0x81, "intr", 10), Endpoint(0x02, "intr", 10))),
            ])
            label = 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = t
            self._axis_protocol(t, dur - t, bus, dev, lines)

        elif profile == "axis_identity":
            # Declares storage it never uses, and otherwise behaves EXACTLY as
            # a benign keyboard -- same generator, same constants. This is the
            # honest boundary case: behavioural features should fail here and
            # identity features should carry it alone.
            d = self._descriptor("keyboard", bus, dev, [
                self._iface(CLASS_HID, 0x01, 0x01, self._HID_EPS),
                self._iface(CLASS_MASS_STORAGE, 0x06, 0x50, self._STORAGE_EPS),
            ])
            label = 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid, n_ifaces=2)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = t
            self._human_typing(t, dur - t, bus, dev, lines)

        elif profile == "axis_diffuse":
            # An ORDINARY keyboard descriptor: the diffuse deviation is in
            # traffic shape, not in what the device declares.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = t
            self._axis_diffuse(t, dur - t, bus, dev, lines)

        else:
            raise ValueError(f"unknown profile {profile!r}; expected one of {ALL_PROFILES}")

        lines.sort(key=lambda ln: int(ln.split()[1]))
        return SimulatedSession(sid=sid, profile=profile, label=label, descriptor=d,
                                lines=lines, onset=onset, duration=dur)

    # ------------------------------------------------------------------
    # multi-device host sessions (contract 3.0.0, cross-device correlation)
    # ------------------------------------------------------------------

    #: Probability that a host has a human actively using a mouse alongside the
    #: keyboard under examination.
    #:
    #: **The same value is used whether or not the host's keyboard is malicious,
    #: and that is the entire leakage guard.** If attacked hosts were lonelier
    #: than benign ones, "no concurrent activity" would separate them perfectly
    #: and `concurrent_device_rate` would be the next log_time_since_enum: a
    #: feature that encodes how the corpus was built rather than how a device
    #: behaves. Both cases must occur on both sides -- a person typing at a
    #: machine with no mouse attached is ordinary, and a BadUSB plugged into a
    #: workstation whose owner is still working is the realistic attack.
    P_COMPANION = 0.6

    def host_session(self, hid: str, keyboard_profile: str,
                     duration: float | None = None) -> list[SimulatedSession]:
        """One host: a keyboard (benign or malicious) and maybe a companion.

        Returns every device's session on a shared timeline, so a caller can
        join them per window to compute host-level features.
        """
        dur = duration if duration is not None else self.rng.uniform(*DURATION_RANGE)
        out = [self.session(f"{hid}K", keyboard_profile, duration=dur)]
        if self.rng.random() < self.P_COMPANION:
            out.append(self.session(f"{hid}M", "mouse", duration=dur))
        return out

    def plan(self, n_benign: int = 210, n_attack: int = 140, *,
             benign_profiles: tuple[str, ...] = BENIGN_PROFILES,
             attack_profiles: tuple[str, ...] = ATTACK_PROFILES,
             ) -> list[tuple[str, str]]:
        """A (session_id, profile) schedule, so a caller can generate, featurise
        and discard one session at a time instead of holding every URB in RAM.

        The profile pools are parameters so the N1 fusion ablation can build a
        corpus from ``AXIS_PROFILES`` without the headline corpus changing.
        """
        items = [(f"S{i:04d}", self.rng.choice(benign_profiles)) for i in range(n_benign)]
        items += [(f"A{j:04d}", self.rng.choice(attack_profiles)) for j in range(n_attack)]
        self.rng.shuffle(items)
        return items

    def plan_balanced(self, per_profile: int, *, benign_profiles, attack_profiles,
                      benign_multiple: int = 1) -> list[tuple[str, str]]:
        """An exactly-balanced schedule: ``per_profile`` sessions of each.

        ``plan`` samples profiles at random, which leaves per-profile counts
        uneven — fine at corpus scale, but the fusion ablation reports a
        detection rate *per axis*, and an axis that happens to draw 11 sessions
        instead of 20 carries a noise floor almost twice as wide. Balance is
        what makes the per-axis cells comparable to each other.
        """
        items = [(f"S{i:04d}", p) for p in benign_profiles
                 for i in range(per_profile * benign_multiple)]
        items = [(f"S{i:04d}", p) for i, (_, p) in enumerate(items)]
        atk = [p for p in attack_profiles for _ in range(per_profile)]
        items += [(f"A{j:04d}", p) for j, p in enumerate(atk)]
        self.rng.shuffle(items)
        return items
