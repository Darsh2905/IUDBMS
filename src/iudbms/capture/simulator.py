"""
L0 — synthetic device traffic, as an EventSource.

Emits real usbmon on-wire text plus a real ``DeviceDescriptor``, so everything
downstream is exercised through the identical code path as a live capture. The
simulator is deliberately *not* privileged: it is one ``EventSource`` among
usbmon, replay and eBPF, which is what stops the pipeline quietly depending on
its quirks.

**Nothing measured here is a claim about real-world accuracy.** Attack families
are generated by the same code the feature set was designed against, so
per-profile detection rates are optimistic by construction. See plan §10.

Fidelity fixes vs the Sprint-0 simulator (CLAUDE.md §4 defects 3 and 4)
----------------------------------------------------------------------

* **Submissions are emitted.** Real usbmon prints an ``S`` and a ``C`` for every
  URB; the old simulator printed only completions. L2 counts completions only
  (see ``features.extractor``), so this changes no baseline — it just stops the
  trace being unfalsifiably unlike the real thing.
* **Control traffic exists.** Every device enumerates (GET_DESCRIPTOR,
  SET_CONFIGURATION, ...) and HID devices issue SET_IDLE/GET_REPORT. The old
  corpus contained none, which made ``frac_ctrl`` a constant-zero feature —
  1 of 28 features carrying no information at all.
* **One duration distribution for every profile.** ``staged_delay`` used to
  redraw ``uniform(65, 85)`` while everything else drew ``uniform(40, 85)``,
  so any window past t≈62 s was disproportionately malicious and
  ``log_time_since_enum`` was a shortcut. It drew a longer session *because*
  the attack needs a long dwell before onset, so the fix is to make its onset
  proportional to session length (0.45-0.62 of it) rather than an absolute
  30-45 s. The dwell semantics survive; the leak does not.
* **usbmon-accurate addressing.** Bus numbers are printed unpadded and device
  numbers zero-padded to three digits, as ``mon_text.c`` does.
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from typing import Iterator

import numpy as np

from ..contract import (
    CLASS_AUDIO,
    CLASS_HID,
    CLASS_MASS_STORAGE,
    CLASS_VIDEO,
    CaptureStats,
    DeviceDescriptor,
    Endpoint,
    Interface,
    URBEvent,
)
from .usbmon import UsbmonParser

__all__ = [
    "Simulator", "SimulatedSession", "SimulatedSource",
    "BENIGN_PROFILES", "ATTACK_PROFILES", "ALL_PROFILES",
]

BENIGN_PROFILES = ("keyboard", "mouse", "mass_storage", "webcam", "audio")
ATTACK_PROFILES = ("hid_injection", "identity_switch", "staged_delay",
                   "class_exfil", "mimicry")
ALL_PROFILES = BENIGN_PROFILES + ATTACK_PROFILES

CTRL, ISO, INTR, BULK = "C", "Z", "I", "B"

VENDORS = {
    "keyboard":     [(0x046D, 0xC31C), (0x413C, 0x2113), (0x1A2C, 0x2D23)],
    "mouse":        [(0x046D, 0xC077), (0x093A, 0x2510)],
    "mass_storage": [(0x0781, 0x5583), (0x0951, 0x1666), (0x090C, 0x1000)],
    "webcam":       [(0x046D, 0x0825), (0x1BCF, 0x2C99)],
    "audio":        [(0x0B05, 0x1A00), (0x046D, 0x0A38)],
}

#: One duration distribution for every profile, benign and malicious alike.
#: Do not special-case a profile here; see the module docstring.
DURATION_RANGE = (40.0, 85.0)


@dataclass
class SimulatedSession:
    sid: str
    profile: str
    label: int                      # 0 benign, 1 malicious
    descriptor: DeviceDescriptor
    lines: list[str] = field(default_factory=list)
    onset: float | None = None      # seconds from enumeration
    duration: float = 0.0

    def events(self) -> list[URBEvent]:
        return list(UsbmonParser().feed(self.lines))


class SimulatedSource:
    """An :class:`~iudbms.contract.EventSource` over one simulated session."""

    def __init__(self, session: SimulatedSession):
        self._session = session
        self._parser = UsbmonParser()

    @property
    def stats(self) -> CaptureStats:
        return self._parser.stats

    def descriptor(self, device_key: str) -> DeviceDescriptor:
        if device_key != self._session.descriptor.device_key:
            raise KeyError(device_key)
        return self._session.descriptor

    def events(self) -> Iterator[URBEvent]:
        yield from self._parser.feed(self._session.lines)


def _hid_report(rng: random.Random, code: int | None = None) -> bytes:
    """8-byte boot-protocol keyboard report."""
    mod = rng.choice([0, 0, 0, 2, 32])
    key = code if code is not None else rng.randint(4, 40)
    return bytes([mod, 0, key, 0, 0, 0, 0, 0])


def _mouse_report(rng: random.Random) -> bytes:
    return bytes([rng.randint(0, 3), rng.randint(0, 255), rng.randint(0, 255), 0])


class Simulator:
    def __init__(self, seed: int = 0):
        self.rng = random.Random(seed)
        self.np_rng = np.random.default_rng(seed)
        self._tag = 0xFFFF880100000000
        self._devnum = 2
        self._frame = 2048

    def _next_tag(self) -> int:
        self._tag += 0x40
        return self._tag

    # ------------------------------------------------------------------
    # usbmon line emission
    # ------------------------------------------------------------------

    def _urb(self, lines, ts, ttype, direction, bus, dev, ep, payload,
             length=None, interval=None, capture=True):
        """Emit the S and C lines for one URB, as real usbmon does.

        Real usbmon prints a submission and a completion for every URB. L2
        counts completions only, so the submission adds realism without
        changing any feature — which is exactly the property that makes this
        fix safe (CLAUDE.md §3, milestone 3 notes).
        """
        tag = self._next_tag()
        n = length if length is not None else len(payload)
        d = "i" if direction == "in" else "o"
        sub_us = int(max(ts - 0.00008, 0.0) * 1e6)
        cmp_us = int(ts * 1e6)

        if ttype == INTR:
            s_status, c_status = f"-115:{interval or 8}", f"0:{interval or 8}"
        elif ttype == ISO:
            self._frame += 1
            s_status = f"-115:1:{self._frame}"
            c_status = f"0:1:{self._frame}:0"
        else:
            s_status, c_status = "-115", "0"

        # Submission: an IN URB has no data yet ("<"); an OUT URB carries it.
        if direction == "in":
            lines.append(f"{tag:016x} {sub_us} S {ttype}{d}:{bus}:{dev:03d}:{ep} "
                         f"{s_status} {n} <")
        else:
            body = f"= {payload.hex()}" if payload else "-"
            lines.append(f"{tag:016x} {sub_us} S {ttype}{d}:{bus}:{dev:03d}:{ep} "
                         f"{s_status} {n} {body}")

        # Completion: "=" only when the kernel actually captured the payload.
        if capture and payload:
            body = f"= {payload.hex()}"
        else:
            body = "-" if n > 0 else ""
        lines.append(f"{tag:016x} {cmp_us} C {ttype}{d}:{bus}:{dev:03d}:{ep} "
                     f"{c_status} {n} {body}".rstrip())

    def _control(self, lines, ts, bus, dev, *, req_type, request,
                 value=0, index=0, length=0, payload=b"", direction="in"):
        """A control transfer: SETUP submission plus its completion."""
        tag = self._next_tag()
        d = "i" if direction == "in" else "o"
        sub_us = int(max(ts - 0.00008, 0.0) * 1e6)
        lines.append(
            f"{tag:016x} {sub_us} S C{d}:{bus}:{dev:03d}:0 "
            f"s {req_type:02x} {request:02x} {value:04x} {index:04x} {length:04x} "
            f"{length} " + ("<" if direction == "in" else (f"= {payload.hex()}" if payload else "-"))
        )
        body = f"= {payload.hex()}" if payload else ""
        lines.append(f"{tag:016x} {int(ts * 1e6)} C C{d}:{bus}:{dev:03d}:0 0 "
                     f"{len(payload) if payload else length} {body}".rstrip())

    def _enumerate(self, lines, bus, dev, vid, pid, n_ifaces=1):
        """The control burst every device performs at attachment.

        This is why frac_ctrl is a live feature rather than a constant zero.
        """
        t = 0.0
        dev_desc = bytes([18, 1, 0, 2, 0, 0, 0, 64,
                          vid & 0xFF, vid >> 8, pid & 0xFF, pid >> 8,
                          0, 1, 1, 2, 3, 1])
        seq = [
            (0x80, 0x06, 0x0100, 0, 18, dev_desc),                      # GET device desc
            (0x80, 0x06, 0x0200, 0, 9, bytes([9, 2, 34, n_ifaces, 1, 0, 0xA0, 50, 0])),
            (0x80, 0x06, 0x0200, 0, 34, bytes(34)),                     # full config
            (0x80, 0x06, 0x0300, 0, 4, bytes([4, 3, 9, 4])),            # string: langid
            (0x80, 0x06, 0x0302, 0x0409, 16, bytes(16)),                # string: product
            (0x00, 0x09, 0x0001, 0, 0, b""),                            # SET_CONFIGURATION
        ]
        for req_type, request, value, index, length, payload in seq:
            t += float(self.np_rng.uniform(0.0008, 0.004))
            self._control(lines, t, bus, dev, req_type=req_type, request=request,
                          value=value, index=index, length=length, payload=payload,
                          direction="in" if req_type & 0x80 else "out")
        return t

    def _hid_class_setup(self, lines, t, bus, dev):
        """SET_IDLE + GET_REPORT — what a HID driver does after enumeration."""
        t += float(self.np_rng.uniform(0.001, 0.003))
        self._control(lines, t, bus, dev, req_type=0x21, request=0x0A,
                      value=0, index=0, length=0, direction="out")
        t += float(self.np_rng.uniform(0.001, 0.003))
        self._control(lines, t, bus, dev, req_type=0xA1, request=0x01,
                      value=0x0100, index=0, length=8, payload=bytes(8))
        return t

    # ------------------------------------------------------------------
    # benign traffic generators
    # ------------------------------------------------------------------

    def _human_typing(self, t, dur, bus, dev, lines, ep=1):
        """Human keystrokes: log-normal IATs, word bursts, think-pauses."""
        end = t + dur
        while t < end:
            for _ in range(self.rng.randint(3, 9)):
                t += min(float(self.np_rng.lognormal(-1.9, 0.55)), 1.2)
                if t >= end:
                    break
                self._urb(lines, t, INTR, "in", bus, dev, ep,
                          _hid_report(self.rng), interval=10)
            t += self.rng.uniform(0.4, 3.0)
        return t

    def _mouse_motion(self, t, dur, bus, dev, lines, ep=1):
        end = t + dur
        while t < end:
            for _ in range(self.rng.randint(10, 60)):
                t += max(0.002, float(self.np_rng.normal(0.010, 0.004)))
                if t >= end:
                    break
                self._urb(lines, t, INTR, "in", bus, dev, ep,
                          _mouse_report(self.rng), interval=8)
            t += self.rng.uniform(0.3, 2.5)
        return t

    def _bulk_io(self, t, dur, bus, dev, lines, ep_in=1, ep_out=2, rate=(10, 60)):
        end = t + dur
        while t < end:
            for _ in range(self.rng.randint(*rate)):
                t += max(0.0002, float(self.np_rng.normal(0.0016, 0.0006)))
                if t >= end:
                    break
                out = self.rng.random() < 0.35
                size = self.rng.choice([512, 1024, 2048, 4096])
                # usbmon captures a short prefix of a large bulk transfer.
                self._urb(lines, t, BULK, "out" if out else "in", bus, dev,
                          ep_out if out else ep_in,
                          bytes(self.np_rng.integers(0, 255, 16, dtype=np.uint8)),
                          length=size)
            t += self.rng.uniform(0.5, 4.0)
        return t

    def _iso_stream(self, t, dur, bus, dev, lines, ep=3, period=0.008, size=3072):
        end = t + dur
        while t < end:
            t += period * self.rng.uniform(0.95, 1.05)
            if t >= end:
                break
            self._urb(lines, t, ISO, "in", bus, dev, ep,
                      bytes(self.np_rng.integers(0, 255, 12, dtype=np.uint8)),
                      length=size)
        return t

    # ------------------------------------------------------------------
    # attack traffic generators
    # ------------------------------------------------------------------

    def _injected_typing(self, t, dur, bus, dev, lines, ep=1,
                         mean_iat=0.0045, jitter=0.14):
        """Programmatic HID injection: fast, near-constant IAT, scripted codes."""
        end = t + dur
        script = [self.rng.randint(4, 40) for _ in range(self.rng.randint(20, 40))]
        i = 0
        while t < end:
            t += max(0.0008, float(self.np_rng.normal(mean_iat, mean_iat * jitter)))
            if t >= end:
                break
            self._urb(lines, t, INTR, "in", bus, dev, ep,
                      _hid_report(self.rng, script[i % len(script)]), interval=10)
            i += 1
            if i % 200 == 0:
                t += self.rng.uniform(0.05, 0.20)     # GUI-launch wait
        return t

    def _mimicry_typing(self, t, dur, bus, dev, lines, ep=1):
        """Adaptive adversary: throttles to the SAME log-normal inter-arrival
        distribution as a human, so every timing feature is indistinguishable
        per window. What it does not fake is structure — a fixed script (low
        payload novelty, high repeat ratio) and a cadence that never stops for
        the multi-second idles a real user produces. Both tells are weak per
        window and separate only over a sequence, which is Stage 2's burden."""
        end = t + dur
        script = [self.rng.randint(4, 40) for _ in range(self.rng.randint(24, 48))]
        i = 0
        while t < end:
            for _ in range(self.rng.randint(3, 9)):
                t += min(float(self.np_rng.lognormal(-1.9, 0.55)), 1.2)
                if t >= end:
                    break
                self._urb(lines, t, INTR, "in", bus, dev, ep,
                          _hid_report(self.rng, script[i % len(script)]), interval=10)
                i += 1
            t += self.rng.uniform(0.35, 1.1)          # human pauses are 0.4-3.0 s
        return t

    def _covert_bulk_out(self, t, dur, bus, dev, lines, ep=2):
        """HID-declared device pushing bulk OUT: class/behaviour mismatch."""
        end = t + dur
        while t < end:
            t += max(0.0008, float(self.np_rng.normal(0.0035, 0.0006)))
            if t >= end:
                break
            self._urb(lines, t, BULK, "out", bus, dev, ep,
                      bytes(self.np_rng.integers(0, 255, 16, dtype=np.uint8)),
                      length=2048)
        return t

    # ------------------------------------------------------------------
    # session assembly
    # ------------------------------------------------------------------

    def _iface(self, cls, sub, proto, eps, first_seen=0.0) -> Interface:
        return Interface(bInterfaceClass=cls, bInterfaceSubClass=sub,
                         bInterfaceProtocol=proto, endpoints=tuple(eps),
                         first_seen_ts=first_seen)

    def _descriptor(self, vendor_key, bus, devnum, ifaces) -> DeviceDescriptor:
        vid, pid = self.rng.choice(VENDORS[vendor_key])
        return DeviceDescriptor(
            bus=bus, devnum=devnum, vid=vid, pid=pid, bDeviceClass=0x00,
            serial_present=self.rng.random() < 0.7,
            manufacturer=vendor_key, product=vendor_key,
            interfaces=tuple(ifaces),
        )

    _HID_EPS = (Endpoint(0x81, "intr", 10),)
    _STORAGE_EPS = (Endpoint(0x81, "bulk"), Endpoint(0x02, "bulk"))

    def session(self, sid: str, profile: str, duration: float | None = None
                ) -> SimulatedSession:
        rng = self.rng
        bus = rng.randint(1, 3)
        dev = self._devnum
        self._devnum = 2 + (self._devnum - 1) % 120
        lines: list[str] = []
        onset: float | None = None

        # ONE duration distribution for every profile. If malicious sessions
        # ran longer than benign ones the models could separate them on session
        # length alone, which is leakage rather than detection (plan §5).
        dur = duration if duration is not None else rng.uniform(*DURATION_RANGE)

        def hid_desc():
            return self._descriptor("keyboard", bus, dev,
                                    [self._iface(CLASS_HID, 0x01, 0x01, self._HID_EPS)])

        if profile == "keyboard":
            d, label = hid_desc(), 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            self._human_typing(t, dur - t, bus, dev, lines)

        elif profile == "mouse":
            d = self._descriptor("mouse", bus, dev,
                                 [self._iface(CLASS_HID, 0x01, 0x02,
                                              (Endpoint(0x81, "intr", 8),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            self._mouse_motion(t, dur - t, bus, dev, lines)

        elif profile == "mass_storage":
            d = self._descriptor("mass_storage", bus, dev,
                                 [self._iface(CLASS_MASS_STORAGE, 0x06, 0x50,
                                              self._STORAGE_EPS)])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._bulk_io(t, dur - t, bus, dev, lines)

        elif profile == "webcam":
            d = self._descriptor("webcam", bus, dev,
                                 [self._iface(CLASS_VIDEO, 0x01, 0x00,
                                              (Endpoint(0x83, "iso"),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._iso_stream(t, dur - t, bus, dev, lines)

        elif profile == "audio":
            d = self._descriptor("audio", bus, dev,
                                 [self._iface(CLASS_AUDIO, 0x02, 0x00,
                                              (Endpoint(0x83, "iso"),))])
            label = 0
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            self._iso_stream(t, dur - t, bus, dev, lines, period=0.005, size=192)

        elif profile == "hid_injection":
            # Descriptor is INDISTINGUISHABLE from a real keyboard, which is
            # what defeats USBGuard-style whitelisting entirely.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(1.5, 4.0)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._injected_typing(onset, dur - onset, bus, dev, lines)

        elif profile == "identity_switch":
            # Enumerates as storage, later exposes an HID interface and injects.
            onset = rng.uniform(15, 30)
            d = self._descriptor("mass_storage", bus, dev, [
                self._iface(CLASS_MASS_STORAGE, 0x06, 0x50, self._STORAGE_EPS),
                self._iface(CLASS_HID, 0x01, 0x01, (Endpoint(0x83, "intr", 10),),
                            first_seen=onset),
            ])
            label = 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid, n_ifaces=2)
            self._bulk_io(t, onset - t, bus, dev, lines)
            # the late interface enumerates its own HID class requests
            self._hid_class_setup(lines, onset, bus, dev)
            self._injected_typing(onset, dur - onset, bus, dev, lines, ep=3)

        elif profile == "staged_delay":
            # Passes as a human-driven keyboard for a long dwell, then fires.
            # Onset is a FRACTION of the session, not an absolute 30-45 s: the
            # absolute form forced a longer duration draw and leaked the label
            # through session length (CLAUDE.md §4 defect 4).
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = dur * rng.uniform(0.45, 0.62)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._injected_typing(onset, dur - onset, bus, dev, lines,
                                  mean_iat=0.004, jitter=0.25)

        elif profile == "mimicry":
            # Hardest case: correct keyboard descriptor AND human-calibrated
            # timing. Only structural and long-horizon cues remain.
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(4, 12)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._mimicry_typing(onset, dur - onset, bus, dev, lines)

        elif profile == "class_exfil":
            d, label = hid_desc(), 1
            t = self._enumerate(lines, bus, dev, d.vid, d.pid)
            t = self._hid_class_setup(lines, t, bus, dev)
            onset = rng.uniform(5, 12)
            self._human_typing(t, onset - t, bus, dev, lines)
            self._covert_bulk_out(onset, dur - onset, bus, dev, lines)

        else:
            raise ValueError(f"unknown profile {profile!r}; expected one of {ALL_PROFILES}")

        lines.sort(key=lambda ln: int(ln.split()[1]))
        return SimulatedSession(sid=sid, profile=profile, label=label, descriptor=d,
                                lines=lines, onset=onset, duration=dur)

    def plan(self, n_benign: int = 210, n_attack: int = 140) -> list[tuple[str, str]]:
        """A (session_id, profile) schedule, so a caller can generate, featurise
        and discard one session at a time instead of holding every URB in RAM."""
        items = [(f"S{i:04d}", self.rng.choice(BENIGN_PROFILES)) for i in range(n_benign)]
        items += [(f"A{j:04d}", self.rng.choice(ATTACK_PROFILES)) for j in range(n_attack)]
        self.rng.shuffle(items)
        return items
